import fs from 'node:fs';
const p = '<install>\AppData\\Local\\Programs\\DSH NEXT\\resources\\app.asar';
const fd = fs.openSync(p, 'r');
const h = Buffer.alloc(16);
fs.readSync(fd, h, 0, 16, 0);
const headerSize = h.readUInt32LE(4);
const jsonSize = h.readUInt32LE(12);
const hb = Buffer.alloc(jsonSize);
fs.readSync(fd, hb, 0, jsonSize, 16);
const s = hb.toString('utf8');
const hdr = JSON.parse(s);
const e = hdr.files['lib']['files']['web-document.js'];
const stat = fs.fstatSync(fd);
console.log('jsonSize', jsonSize, 'headerSize', headerSize, 'base', 8 + headerSize, 'fileSize', stat.size);
console.log('ENTRY', JSON.stringify(e, null, 2));
console.log('offsetEntries', (s.match(/"offset"/g) || []).length);
console.log('minifiedJsonBytes', Buffer.byteLength(JSON.stringify(hdr)));
console.log('slackBytes', jsonSize - Buffer.byteLength(JSON.stringify(hdr)));
console.log('libKeys', Object.keys(hdr.files['lib'].files).slice(0, 20));
fs.closeSync(fd);
